"""NexusForge database migrations."""

# Alembic commands for database migrations

# Initialize migrations:
# alembic init backend/app/migrations

# Generate a migration:
# alembic revision --autogenerate -m "Migration name"

# Apply migrations:
# alembic upgrade head

# Rollback migrations:
# alembic downgrade -1

# Show current revision:
# alembic current

# Show migration history:
# alembic history