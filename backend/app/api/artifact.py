@router.get("/{artifact_id}", response_model=ArtifactResponse, summary="Get artifact details")
async def get_artifact(
    artifact_id: str,
    db_session: AsyncSession = Depends(get_db_session),
    current_user = Depends(get_current_user),
):
    """Get full details of a single artifact.
    
    Shows content preview, metadata, versions, and links.
    """
    from uuid import UUID
    try:
        uid = UUID(artifact_id)
    except ValueError:
        uid = None
    
    if uid:
        result = await db_session.execute(select(Artifact).where(Artifact.id == uid))
    else:
        result = await db_session.execute(select(Artifact).where(Artifact.id == artifact_id))
    
    artifact = result.scalar_one_or_none()
    if not artifact:
        raise HTTPException(status_code=404, detail="Artifact not found")
    
    return artifact.to_dict()


@router.post("/{artifact_id}/versions", response_model=ArtifactResponse, summary="Create new artifact version")
async def create_version(
    artifact_id: str,
    data: ArtifactUpdate,
    db_session: AsyncSession = Depends(get_db_session),
    current_user = Depends(get_current_user),
):
    """Create a new version of an artifact, preserving history.
    
    The UI shows version history for tracking evolution.
    """
    from uuid import uuid4
    
    from sqlalchemy import func
    
    result = await db_session.execute(select(Artifact).where(Artifact.id == artifact_id))
    original = result.scalar_one_or_none()
    if not original:
        raise HTTPException(status_code=404, detail="Artifact not found")
    
    # Get current max version for this artifact
    version_result = await db_session.execute(
        select(func.max(Artifact.version)).where(Artifact.id == artifact_id)
    )
    max_version = version_result.scalar() or 0
    
    new_artifact = Artifact(
        id=str(uuid4()),
        project_id=original.project_id,
        task_id=original.task_id,
        name=data.name or original.name,
        type=original.type,
        version=max_version + 1,
        description=data.description or original.description,
        path=data.path or original.path,
        size=data.size or original.size,
        mime_type=original.mime_type,
        checksum=data.checksum or original.checksum,
        author_id=str(current_user.get("id")) if current_user else original.author_id,
        created_at=datetime.now(timezone.utc),
        is_public=original.is_public,
        extra_data={"parent_version": original.version, "parent_id": original.id},
    )
    
    db_session.add(new_artifact)
    await db_session.commit()
    await db_session.refresh(new_artifact)
    
    return new_artifact.to_dict()


